def _bearer(keys: dict[str, Any], clerk_user_id: str) -> str:
    return _sign(
        keys["priv_pem"],
        {
            "sub": clerk_user_id,
            "email": f"{clerk_user_id}@t.io",
            "exp": int(time.time()) + 3600,
        },
        keys["kid"],
    )


async def _seed_user(
    factory: Any,
    *,
    clerk_id: str,
    is_admin: bool = False,
    stripe_customer_id: str | None = None,
) -> uuid6.UUID:
    async with factory() as db:
        user = User(
            id=uuid6.uuid7(),
            clerk_user_id=clerk_id,
            email=f"{clerk_id}@t.io",
            is_admin=is_admin,
            stripe_customer_id=stripe_customer_id,
        )
        db.add(user)
        await db.commit()
        return user.id


async def _seed_profile(
    factory: Any, *, user_id: uuid6.UUID, display_name: str
) -> uuid6.UUID:
    async with factory() as db:
        prof = DriverProfile(
            id=uuid6.uuid7(),
            user_id=user_id,
            display_name=display_name,
            skill_level="intermediate",
            cohort_opt_in=True,
        )
        db.add(prof)
        await db.commit()
        return prof.id


async def _seed_session(
    factory: Any, *, driver_id: uuid6.UUID, manifest: dict[str, Any]
) -> uuid6.UUID:
    async with factory() as db:
        s = Session(
            id=uuid6.uuid7(),
            driver_id=driver_id,
            manifest=manifest,
        )
        db.add(s)
        await db.commit()
        return s.id


def _hdrs(ca: dict[str, Any], clerk_id: str) -> dict[str, str]:
    return {"Authorization": f"Bearer {_bearer(ca['keys'], clerk_id)}"}


