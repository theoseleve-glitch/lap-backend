def test_export_requires_authentication(
    configured_app: dict[str, Any],  # noqa: ARG001
) -> None:
    """A GDPR export discloses PII — anonymous request must
    be refused. 401 (not 403) because there is no claim of
    identity at all yet."""
    with TestClient(app) as client:
        resp = client.post("/api/v1/me/export")
    assert resp.status_code == 401


# -- response shape ----------------------------------------------


def test_export_returns_zip_content_type_and_disposition(
    configured_app: dict[str, Any],
) -> None:
    """Browsers and CLIs both rely on Content-Disposition with
    a .zip filename to save the body to disk rather than render
    it. Pin the media type AND the disposition header so a
    future change to FileResponse vs StreamingResponse can't
    silently break the download UX."""
    asyncio.run(_seed_user(configured_app["factory"], clerk_id="export194a"))
    with TestClient(app) as client:
        resp = client.post(
            "/api/v1/me/export",
            headers=_hdrs(configured_app, "export194a"),
        )
    assert resp.status_code == 200, resp.text
    assert resp.headers["content-type"] == "application/zip"
    disposition = resp.headers.get("content-disposition", "")
    assert "attachment" in disposition.lower()
    assert ".zip" in disposition.lower()


def test_export_body_is_a_valid_zip(
    configured_app: dict[str, Any],
) -> None:
    """The bytes must parse as a real ZIP — not just a JSON
    blob with the wrong content-type. zipfile.is_zipfile gives
    us the canonical answer."""
    asyncio.run(_seed_user(configured_app["factory"], clerk_id="export194b"))
    with TestClient(app) as client:
        resp = client.post(
            "/api/v1/me/export",
            headers=_hdrs(configured_app, "export194b"),
        )
    assert resp.status_code == 200
    buf = io.BytesIO(resp.content)
    assert zipfile.is_zipfile(buf), "body is not a ZIP archive"


# -- contents ----------------------------------------------------


def _open_zip(content: bytes) -> zipfile.ZipFile:
    return zipfile.ZipFile(io.BytesIO(content))


def test_export_contains_user_json_with_pii(
    configured_app: dict[str, Any],
) -> None:
    """Article 20 exports center on PII: email + identifiers.
    The user.json file is the load-bearing entry; without it
    the export tells the user nothing about themselves."""
    user_id = asyncio.run(
        _seed_user(configured_app["factory"], clerk_id="export194c")
    )
    with TestClient(app) as client:
        resp = client.post(
            "/api/v1/me/export",
            headers=_hdrs(configured_app, "export194c"),
        )
    zf = _open_zip(resp.content)
    assert "user.json" in zf.namelist()
    user_payload = json.loads(zf.read("user.json"))
    assert user_payload["email"] == "export194c@t.io"
    assert user_payload["clerk_user_id"] == "export194c"
    assert user_payload["id"] == str(user_id)
    assert "created_at" in user_payload


def test_export_user_json_redacts_internal_flags(
    configured_app: dict[str, Any],
) -> None:
    """is_admin / stripe_customer_id are operational state, not
    user-facing data. Including them in a portability export
    leaks billing identifiers and lets a malicious export-then-
    delete-then-recreate flow learn admin status. Pin the
    redaction so a "let me just include everything" PR fails."""
    asyncio.run(
        _seed_user(
            configured_app["factory"],
            clerk_id="export194d",
            is_admin=True,
            stripe_customer_id="cus_LEAK_ME_NOT",
        )
    )
    with TestClient(app) as client:
        resp = client.post(
            "/api/v1/me/export",
            headers=_hdrs(configured_app, "export194d"),
        )
    zf = _open_zip(resp.content)
    payload = json.loads(zf.read("user.json"))
    assert "is_admin" not in payload, (
        "is_admin must be redacted from GDPR export"
    )
    assert "stripe_customer_id" not in payload, (
        "stripe_customer_id must be redacted from GDPR export"
    )
    assert "is_waitlist" not in payload, (
        "is_waitlist must be redacted from GDPR export"
    )


