"""T194 (sprint2-backend) — GDPR Article 20 data export.

POST /api/v1/me/export delivers a ZIP of the calling user's
personal data in a structured, machine-readable format. This
satisfies the "right to data portability" obligation: the user
can take their data with them.

What's in scope (data the user provided OR generated by their
use of the service):
  - user.json: the caller's User row (PII: email, clerk_user_id,
    created_at). Internal flags like is_admin / is_waitlist /
    stripe_customer_id are deliberately redacted — they're
    operational state, not data the user is entitled to.
  - driver_profile.json: their DriverProfile if one exists.
    Absent file (not empty file) when no profile has been
    created — easier for an importer to detect.
  - sessions.json: array of their Session rows (id, created_at,
    status, manifest). Other drivers' sessions never appear.

Pinned behaviors below correspond 1:1 to the legal contract.
A regression in any one — wrong shape, leaked admin flag,
cross-user data — fails this file before it can ship.
"""

