def test_export_sessions_json_lists_caller_sessions_only(
    configured_app: dict[str, Any],
) -> None:
    """Cross-user isolation is the contract that GDPR is
    weakest at if violated. Seed TWO drivers; verify the
    caller's export contains their session ids and not the
    other driver's. This is the regression that, if it broke,
    would land in a regulator's complaint."""
    factory = configured_app["factory"]
    me_id = asyncio.run(_seed_user(factory, clerk_id="export194g_me"))
    me_drv = asyncio.run(
        _seed_profile(
            factory, user_id=me_id, display_name="Me",
        )
    )
    other_id = asyncio.run(_seed_user(factory, clerk_id="export194g_them"))
    other_drv = asyncio.run(
        _seed_profile(
            factory, user_id=other_id, display_name="Them",
        )
    )

    mine_session_id = asyncio.run(
        _seed_session(
            factory,
            driver_id=me_drv,
            manifest={"track": "spa", "car": "gt3"},
        )
    )
    theirs_session_id = asyncio.run(
        _seed_session(
            factory,
            driver_id=other_drv,
            manifest={"track": "monza"},
        )
    )

    with TestClient(app) as client:
        resp = client.post(
            "/api/v1/me/export",
            headers=_hdrs(configured_app, "export194g_me"),
        )
    zf = _open_zip(resp.content)
    sessions = json.loads(zf.read("sessions.json"))
    ids = {row["id"] for row in sessions}
    assert str(mine_session_id) in ids, "caller's session missing"
    assert str(theirs_session_id) not in ids, (
        "OTHER user's session leaked into export — "
        "Article 20 violation, would block prod ship"
    )


def test_export_sessions_json_carries_manifest_and_metadata(
    configured_app: dict[str, Any],
) -> None:
    """sessions.json is the largest piece of the export. Pin
    that each row carries id, created_at, status, manifest —
    the four fields a re-importer needs to round-trip."""
    factory = configured_app["factory"]
    user_id = asyncio.run(_seed_user(factory, clerk_id="export194h"))
    drv = asyncio.run(
        _seed_profile(
            factory, user_id=user_id, display_name="P",
        )
    )
    asyncio.run(
        _seed_session(
            factory,
            driver_id=drv,
            manifest={"track": "imola", "session_type": "race"},
        )
    )
    with TestClient(app) as client:
        resp = client.post(
            "/api/v1/me/export",
            headers=_hdrs(configured_app, "export194h"),
        )
    zf = _open_zip(resp.content)
    sessions = json.loads(zf.read("sessions.json"))
    assert len(sessions) == 1
    row = sessions[0]
    for key in ("id", "created_at", "status", "manifest"):
        assert key in row, f"sessions row missing {key!r}"
    assert row["manifest"]["track"] == "imola"
    assert row["manifest"]["session_type"] == "race"


def test_export_with_no_sessions_writes_empty_array_not_missing_file(
    configured_app: dict[str, Any],
) -> None:
    """Empty != absent. A user who has never uploaded a session
    still gets sessions.json = [] so the re-importer doesn't
    crash on a missing file (vs. driver_profile, where absent
    = no profile yet, a different state)."""
    factory = configured_app["factory"]
    user_id = asyncio.run(_seed_user(factory, clerk_id="export194i"))
    asyncio.run(
        _seed_profile(
            factory, user_id=user_id, display_name="Q",
        )
    )
    with TestClient(app) as client:
        resp = client.post(
            "/api/v1/me/export",
            headers=_hdrs(configured_app, "export194i"),
        )
    zf = _open_zip(resp.content)
    assert "sessions.json" in zf.namelist()
    assert json.loads(zf.read("sessions.json")) == []
