"""T019 (sprint2-backend) — bridge link create endpoint.

`POST /api/v1/bridge/links` registers a sim↔real TransferLink
between two of the authenticated driver's sessions. Same shape
covers manual pairings (`created_by="user"`) and auto-detected
suggestions the driver accepted (`created_by="auto"`).

Server fills the three identity fields:
- `id` — UUID7 generated by the ORM default
- `driver_id` — derived from the authenticated user
- `created_at` — server clock (UTC)

Cross-driver isolation: every session_id in the pair must belong
to the authenticated driver. Mixed/unknown ids → 404, mirroring
`sessions.get_session` so callers can't enumerate other drivers'
session ids.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Annotated
from uuid import UUID

import uuid6
from fastapi import APIRouter, Depends, HTTPException, status
from lap_schemas.v1 import TransferLink as TransferLinkSchema
from lap_schemas.v1 import TransferLinkCreate
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.deps import get_current_user, get_db
from infra.orm import DriverProfile as DriverProfileRow
from infra.orm import Session as SessionRow
from infra.orm import TransferLink as TransferLinkRow
from infra.orm import User as UserRow

router = APIRouter(prefix="/api/v1/bridge", tags=["bridge"])


@router.post(
    "/links",
    response_model=TransferLinkSchema,
    status_code=status.HTTP_201_CREATED,
)
async def create_bridge_link(
    body: TransferLinkCreate,
    user: Annotated[UserRow, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
) -> TransferLinkSchema:
    profile = (
        await db.execute(
            select(DriverProfileRow).where(
                DriverProfileRow.user_id == user.id
            )
        )
    ).scalar_one_or_none()
    if profile is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="driver_not_found",
        )

    # All sessions in the pair must belong to this driver. Single
    # IN-clause query: if the count of rows returned is less than
    # the unique count we asked for, at least one is missing or
    # owned by someone else — collapse both cases to 404.
    session_ids = [UUID(str(s)) for s in body.session_pair]
    owned_count = (
        await db.execute(
            select(SessionRow.id)
            .where(SessionRow.id.in_(session_ids))
            .where(SessionRow.driver_id == profile.id)
        )
    ).all()
    if len(owned_count) != len(set(session_ids)):
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="session_not_found",
        )

    link_id = uuid6.uuid7()
    created_at = datetime.now(UTC)
    row = TransferLinkRow(
        id=link_id,
        driver_id=profile.id,
        created_at=created_at,
        created_by=body.created_by,
        session_pair=[str(s) for s in body.session_pair],
        link_reason=body.link_reason,
        shape_match_score=body.shape_match_score,
        intensity_match_score=body.intensity_match_score,
        divergence_points=[
            dp.model_dump(mode="json") for dp in body.divergence_points
        ],
        transferred_skills=list(body.transferred_skills),
        non_transferred_skills=list(body.non_transferred_skills),
        generated_report_id=body.generated_report_id,
    )
    db.add(row)
    await db.commit()

    return TransferLinkSchema(
        id=link_id,
        driver_id=profile.id,
        created_at=created_at,
        created_by=body.created_by,
        session_pair=body.session_pair,
        link_reason=body.link_reason,
        shape_match_score=body.shape_match_score,
        intensity_match_score=body.intensity_match_score,
        divergence_points=body.divergence_points,
        transferred_skills=body.transferred_skills,
        non_transferred_skills=body.non_transferred_skills,
        generated_report_id=body.generated_report_id,
    )


# T020 (sprint2-backend) — full TransferLink for one bridge link
# the authenticated driver owns. 404-not-403 cross-driver
# isolation: same posture as get_session, so callers can't probe
# other drivers' link ids.
@router.get(
    "/links/{link_id}",
    response_model=TransferLinkSchema,
    responses={404: {"description": "transfer_link_not_found"}},
)
async def get_bridge_link(
    link_id: UUID,
    user: Annotated[UserRow, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
) -> TransferLinkSchema:
    profile = (
        await db.execute(
            select(DriverProfileRow).where(
                DriverProfileRow.user_id == user.id
            )
        )
    ).scalar_one_or_none()
    row = (
        await db.execute(
            select(TransferLinkRow).where(
                TransferLinkRow.id == link_id
            )
        )
    ).scalar_one_or_none()
    if row is None or profile is None or row.driver_id != profile.id:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="transfer_link_not_found",
        )
    return _row_to_schema(row)


def _row_to_schema(row: TransferLinkRow) -> TransferLinkSchema:
    return TransferLinkSchema(
        id=row.id,
        driver_id=row.driver_id,
        created_at=row.created_at,
        created_by=row.created_by,
        session_pair=tuple(UUID(s) for s in row.session_pair),
        link_reason=row.link_reason,
        shape_match_score=row.shape_match_score,
        intensity_match_score=row.intensity_match_score,
        divergence_points=tuple(row.divergence_points or []),
        transferred_skills=tuple(row.transferred_skills or []),
        non_transferred_skills=tuple(row.non_transferred_skills or []),
        generated_report_id=row.generated_report_id,
    )
