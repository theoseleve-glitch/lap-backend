"""T019 (sprint2-backend) — bridge link create endpoint.

`POST /api/v1/bridge/links` registers a sim↔real TransferLink
between two of the authenticated driver's sessions. Same shape
covers manual pairings (`created_by="user"`) and auto-detected
suggestions the driver accepted (`created_by="auto"`).

Server fills the three identity fields:
- `id` — UUID7 generated by the ORM default
- `driver_id` — derived from the authenticated user
- `created_at` — server clock (UTC)

Cross-driver isolation: every session_id in the pair must belong
to the authenticated driver. Mixed/unknown ids → 404, mirroring
`sessions.get_session` so callers can't enumerate other drivers'
session ids.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Annotated
from uuid import UUID

import uuid6
from fastapi import APIRouter, Depends, HTTPException, Query, status
from lap_schemas.v1 import BridgeLinkRatingRequest, TransferLinkCreate, TransferLinkList
from lap_schemas.v1 import TransferLink as TransferLinkSchema
from sqlalchemy import delete, func, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.deps import get_current_user, get_db
from infra.orm import CarModel as CarModelRow
from infra.orm import CoachingInsight as CoachingInsightRow
from infra.orm import DriverProfile as DriverProfileRow
from infra.orm import Session as SessionRow
from infra.orm import TrackLayout as TrackLayoutRow
from infra.orm import TransferLink as TransferLinkRow
from infra.orm import User as UserRow

router = APIRouter(prefix="/api/v1/bridge", tags=["bridge"])
# T021 — second router so the driver-scoped path
# /api/v1/driver/:id/bridge/links lives outside the /bridge
# prefix while still cohabiting this module.
driver_router = APIRouter(prefix="/api/v1/driver", tags=["bridge"])

# T021 — pagination defaults match catalog endpoints.
_DEFAULT_LIMIT = 20
_MAX_LIMIT = 100


@router.post(
    "/links",
    response_model=TransferLinkSchema,
    status_code=status.HTTP_201_CREATED,
)
async def create_bridge_link(
    body: TransferLinkCreate,
    user: Annotated[UserRow, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
) -> TransferLinkSchema:
    profile = (
        await db.execute(
            select(DriverProfileRow).where(
                DriverProfileRow.user_id == user.id
            )
        )
    ).scalar_one_or_none()
    if profile is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="driver_not_found",
        )

    # All sessions in the pair must belong to this driver. We
    # fetch the Session rows (not just ids) because T026 needs
    # their manifests for cross-sim track/car validation. If the
    # count of rows is less than the unique count we asked for,
    # at least one is missing or owned by someone else — collapse
    # both cases to 404.
    session_ids = [UUID(str(s)) for s in body.session_pair]
    sessions = (
        (
            await db.execute(
                select(SessionRow)
                .where(SessionRow.id.in_(session_ids))
                .where(SessionRow.driver_id == profile.id)
            )
        )
        .scalars()
        .all()
    )
    if len(sessions) != len(set(session_ids)):
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="session_not_found",
        )

    # T026 (sprint2-backend) — bridge validation. Both sessions
    # must point at the same master_track_id and have the same
    # car_class (the catalog-resolved cross-sim grouping fields,
    # not the per-sim track_id/car_id stored on the manifest).
    # Run *after* the cross-driver check so callers can't probe
    # catalog state across drivers.
    await _validate_pair_bridgeable(db, sessions)

    # T027 (sprint2-backend) — dedup. Same set of session ids
    # can't be linked twice for the same driver. Order-independent
    # (the pair is conceptually a set). Driver-scoped (driver B
    # can link the same pair driver A linked).
    new_pair_set = {str(s) for s in body.session_pair}
    existing_for_driver = (
        (
            await db.execute(
                select(TransferLinkRow).where(
                    TransferLinkRow.driver_id == profile.id
                )
            )
        )
        .scalars()
        .all()
    )
    for link in existing_for_driver:
        if {str(s) for s in link.session_pair} == new_pair_set:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="duplicate_link",
            )

    link_id = uuid6.uuid7()
    created_at = datetime.now(UTC)

    # T028 (sprint2-backend) — server-generated CoachingInsight
    # summarizing the transfer findings. Server-controlled (like
    # id/driver_id/created_at), so any client-supplied
    # `generated_report_id` on the body is ignored — we overwrite
    # with the new insight's id below. Insight points at the
    # primary session (first in pair); the full pair is reachable
    # via the link's session_pair field.
    primary_session_id = UUID(str(body.session_pair[0]))
    insight_id = uuid6.uuid7()
    db.add(
        CoachingInsightRow(
            id=insight_id,
            session_id=primary_session_id,
            driver_id=profile.id,
            created_at=created_at,
            rule_id="bridge.link_created",
            rule_version="v1",
            observation=_summarize_transfer(body),
            evidence=[str(s) for s in body.session_pair],
            likely_cause=None,
            severity=_severity_from_scores(
                body.shape_match_score, body.intensity_match_score
            ),
            confidence=(
                body.shape_match_score + body.intensity_match_score
            )
            / 2.0,
            corner_tag=None,
            suggested_prescription_id=None,
        )
    )

    row = TransferLinkRow(
        id=link_id,
        driver_id=profile.id,
        created_at=created_at,
        created_by=body.created_by,
        session_pair=[str(s) for s in body.session_pair],
        link_reason=body.link_reason,
        shape_match_score=body.shape_match_score,
        intensity_match_score=body.intensity_match_score,
        divergence_points=[
            dp.model_dump(mode="json") for dp in body.divergence_points
        ],
        transferred_skills=list(body.transferred_skills),
        non_transferred_skills=list(body.non_transferred_skills),
        generated_report_id=insight_id,
    )
    db.add(row)
    await db.commit()

    return TransferLinkSchema(
        id=link_id,
        driver_id=profile.id,
        created_at=created_at,
        created_by=body.created_by,
        session_pair=body.session_pair,
        link_reason=body.link_reason,
        shape_match_score=body.shape_match_score,
        intensity_match_score=body.intensity_match_score,
        divergence_points=body.divergence_points,
        transferred_skills=body.transferred_skills,
        non_transferred_skills=body.non_transferred_skills,
        generated_report_id=insight_id,
    )


# T020 (sprint2-backend) — full TransferLink for one bridge link
# the authenticated driver owns. 404-not-403 cross-driver
# isolation: same posture as get_session, so callers can't probe
# other drivers' link ids.
@router.get(
    "/links/{link_id}",
    response_model=TransferLinkSchema,
    responses={404: {"description": "transfer_link_not_found"}},
)
async def get_bridge_link(
    link_id: UUID,
    user: Annotated[UserRow, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
) -> TransferLinkSchema:
    profile = (
        await db.execute(
            select(DriverProfileRow).where(
                DriverProfileRow.user_id == user.id
            )
        )
    ).scalar_one_or_none()
    row = (
        await db.execute(
            select(TransferLinkRow).where(
                TransferLinkRow.id == link_id
            )
        )
    ).scalar_one_or_none()
    if row is None or profile is None or row.driver_id != profile.id:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="transfer_link_not_found",
        )
    return _row_to_schema(row)


# T022 (sprint2-backend) — revoke a bridge link the authenticated
# driver owns. 204 on success, 404 (not 403) for absent/not-owned.
# Hard delete: bridge links are user-curated artifacts; if the
# user wants the analysis back they re-create or re-accept it.
@router.delete(
    "/links/{link_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    responses={404: {"description": "transfer_link_not_found"}},
)
async def delete_bridge_link(
    link_id: UUID,
    user: Annotated[UserRow, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
) -> None:
    profile = (
        await db.execute(
            select(DriverProfileRow).where(
                DriverProfileRow.user_id == user.id
            )
        )
    ).scalar_one_or_none()
    row = (
        await db.execute(
            select(TransferLinkRow).where(
                TransferLinkRow.id == link_id
            )
        )
    ).scalar_one_or_none()
    if row is None or profile is None or row.driver_id != profile.id:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="transfer_link_not_found",
        )
    await db.execute(
        delete(TransferLinkRow).where(TransferLinkRow.id == link_id)
    )
    await db.commit()


# T023 (sprint2-backend) — driver thumbs-up/down on a bridge link's
# usefulness. Server stamps `rated_at` (clients can't backdate, so
# the rule-health audit can trust freshness). Re-rating overwrites
# in place — there's only one rating per link. 404-not-403 on
# absent or not-owned, same posture as get/delete on this router.
@router.post(
    "/links/{link_id}/rate",
    response_model=TransferLinkSchema,
    responses={404: {"description": "transfer_link_not_found"}},
)
async def rate_bridge_link(
    link_id: UUID,
    body: BridgeLinkRatingRequest,
    user: Annotated[UserRow, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
) -> TransferLinkSchema:
    profile = (
        await db.execute(
            select(DriverProfileRow).where(
                DriverProfileRow.user_id == user.id
            )
        )
    ).scalar_one_or_none()
    row = (
        await db.execute(
            select(TransferLinkRow).where(
                TransferLinkRow.id == link_id
            )
        )
    ).scalar_one_or_none()
    if row is None or profile is None or row.driver_id != profile.id:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="transfer_link_not_found",
        )

    row.usefulness_rating = body.rating
    row.rated_at = datetime.now(UTC)
    await db.commit()
    await db.refresh(row)
    return _row_to_schema(row)


def _summarize_transfer(body: TransferLinkCreate) -> str:
    """T028 — observation text on the auto-generated insight.
    Deliberately templated and short; the link itself is the
    rich artifact, the insight is the timeline-visible summary."""
    return (
        f"Sim-real bridge: shape match {body.shape_match_score:.2f}, "
        f"intensity match {body.intensity_match_score:.2f}, "
        f"{len(body.divergence_points)} divergence points across "
        f"{len(body.session_pair)} sessions."
    )


def _severity_from_scores(shape: float, intensity: float) -> str:
    """T028 — inverse mapping: low sim↔real match means a wider
    gap to coach about, so it gets ranked higher in the
    coaching-priority view."""
    avg = (shape + intensity) / 2.0
    if avg < 0.5:
        return "high"
    if avg < 0.75:
        return "medium"
    return "low"


async def _validate_pair_bridgeable(
    db: AsyncSession, sessions: list[SessionRow]
) -> None:
    """T026: enforce that the session pair shares a master_track_id
    and a car_class. Raises 422 with a stable detail string on
    violation.

    Both sessions must have `track_id` and `car_id` in their
    manifest, and both must resolve to existing catalog rows. Any
    of those preconditions failing collapses to a single
    `session_unbridgeable` detail — we don't enumerate which side
    or which field, because the caller already knows their own
    sessions and the per-field reason isn't actionable from the
    API surface.
    """
    track_ids: list[UUID] = []
    car_ids: list[UUID] = []
    for s in sessions:
        manifest = s.manifest or {}
        raw_track = manifest.get("track_id")
        raw_car = manifest.get("car_id")
        if not raw_track or not raw_car:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail="session_unbridgeable",
            )
        track_ids.append(UUID(str(raw_track)))
        car_ids.append(UUID(str(raw_car)))

    track_rows = (
        (
            await db.execute(
                select(TrackLayoutRow).where(
                    TrackLayoutRow.id.in_(track_ids)
                )
            )
        )
        .scalars()
        .all()
    )
    if len(track_rows) != len(set(track_ids)):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="session_unbridgeable",
        )
    masters = {r.master_track_id for r in track_rows}
    if len(masters) != 1:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="incompatible_track",
        )

    car_rows = (
        (
            await db.execute(
                select(CarModelRow).where(CarModelRow.id.in_(car_ids))
            )
        )
        .scalars()
        .all()
    )
    if len(car_rows) != len(set(car_ids)):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="session_unbridgeable",
        )
    classes = {r.car_class for r in car_rows}
    if len(classes) != 1:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="incompatible_car_class",
        )


def _row_to_schema(row: TransferLinkRow) -> TransferLinkSchema:
    return TransferLinkSchema(
        id=row.id,
        driver_id=row.driver_id,
        created_at=row.created_at,
        created_by=row.created_by,
        session_pair=tuple(UUID(s) for s in row.session_pair),
        link_reason=row.link_reason,
        shape_match_score=row.shape_match_score,
        intensity_match_score=row.intensity_match_score,
        divergence_points=tuple(row.divergence_points or []),
        transferred_skills=tuple(row.transferred_skills or []),
        non_transferred_skills=tuple(row.non_transferred_skills or []),
        generated_report_id=row.generated_report_id,
        usefulness_rating=row.usefulness_rating,  # T023
        rated_at=row.rated_at,  # T023
    )


# T021 (sprint2-backend) — paginated driver-scoped index. Sorted
# newest-first so the "recent links" view doesn't need a client
# sort. Cross-driver isolation: path's driver_id must match the
# authenticated user's profile.id, otherwise 404 (not 403) so
# callers can't enumerate drivers.
@driver_router.get(
    "/{driver_id}/bridge/links",
    response_model=TransferLinkList,
    responses={404: {"description": "driver_not_found"}},
)
async def list_driver_bridge_links(
    driver_id: UUID,
    user: Annotated[UserRow, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
    limit: Annotated[int, Query(ge=1, le=_MAX_LIMIT)] = _DEFAULT_LIMIT,
    offset: Annotated[int, Query(ge=0)] = 0,
) -> TransferLinkList:
    profile = (
        await db.execute(
            select(DriverProfileRow).where(
                DriverProfileRow.user_id == user.id
            )
        )
    ).scalar_one_or_none()
    if profile is None or profile.id != driver_id:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="driver_not_found",
        )

    total = (
        await db.execute(
            select(func.count(TransferLinkRow.id)).where(
                TransferLinkRow.driver_id == driver_id
            )
        )
    ).scalar_one()

    rows = (
        (
            await db.execute(
                select(TransferLinkRow)
                .where(TransferLinkRow.driver_id == driver_id)
                .order_by(TransferLinkRow.created_at.desc())
                .limit(limit)
                .offset(offset)
            )
        )
        .scalars()
        .all()
    )
    return TransferLinkList(
        items=tuple(_row_to_schema(r) for r in rows),
        total=int(total),
        limit=limit,
        offset=offset,
    )
