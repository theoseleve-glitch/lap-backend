"""T019 (sprint2-backend) — bridge link create endpoint.

`POST /api/v1/bridge/links` registers a sim↔real TransferLink
between two of the authenticated driver's sessions. Same shape
covers manual pairings (`created_by="user"`) and auto-detected
suggestions the driver accepted (`created_by="auto"`).

Server fills the three identity fields:
- `id` — UUID7 generated by the ORM default
- `driver_id` — derived from the authenticated user
- `created_at` — server clock (UTC)

Cross-driver isolation: every session_id in the pair must belong
to the authenticated driver. Mixed/unknown ids → 404, mirroring
`sessions.get_session` so callers can't enumerate other drivers'
session ids.
"""

