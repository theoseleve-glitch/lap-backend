def _summarize_transfer(body: TransferLinkCreate) -> str:
    """T028 — observation text on the auto-generated insight.
    Deliberately templated and short; the link itself is the
    rich artifact, the insight is the timeline-visible summary."""
    return (
        f"Sim-real bridge: shape match {body.shape_match_score:.2f}, "
        f"intensity match {body.intensity_match_score:.2f}, "
        f"{len(body.divergence_points)} divergence points across "
        f"{len(body.session_pair)} sessions."
    )


def _severity_from_scores(shape: float, intensity: float) -> str:
    """T028 — inverse mapping: low sim↔real match means a wider
    gap to coach about, so it gets ranked higher in the
    coaching-priority view."""
    avg = (shape + intensity) / 2.0
    if avg < 0.5:
        return "high"
    if avg < 0.75:
        return "medium"
    return "low"


async def _load_existing_pair_fingerprints(
    db: AsyncSession, driver_id: UUID
) -> set[frozenset[str]]:
    """T027/T030 — pre-load every TransferLink the driver owns
    into a set of frozenset fingerprints, so dedup is O(1) per
    item. The bulk endpoint loads this once and mutates the set
    as items succeed (within-batch dedup); the single endpoint
    loads it once and discards."""
    rows = (
        (
            await db.execute(
                select(TransferLinkRow.session_pair).where(
                    TransferLinkRow.driver_id == driver_id
                )
            )
        )
        .scalars()
        .all()
    )
    return {frozenset(str(s) for s in pair) for pair in rows}


async def _stage_link(
    db: AsyncSession,
    *,
    profile: DriverProfileRow,
    body: TransferLinkCreate,
    item_sessions: list[SessionRow],
    existing_pairs: set[frozenset[str]],
) -> tuple[TransferLinkSchema, frozenset[str]]:
    """Single-item create logic, shared by the single and bulk
    endpoints. Validates (T026), dedups against the supplied
    existing_pairs set (T027 + within-batch), stages an insight
    (T028), stages the link, and returns the response schema +
    the new pair's fingerprint (so the caller can update its
    dedup set when looping a batch).

    Caller commits.
    """
    await _validate_pair_bridgeable(db, item_sessions)

    new_pair = frozenset(str(s) for s in body.session_pair)
    if new_pair in existing_pairs:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=ErrorCode.DUPLICATE_LINK,
        )

    link_id = uuid6.uuid7()
    created_at = datetime.now(UTC)
    primary_session_id = UUID(str(body.session_pair[0]))
    insight_id = uuid6.uuid7()
    db.add(
        CoachingInsightRow(
            id=insight_id,
            session_id=primary_session_id,
            driver_id=profile.id,
            created_at=created_at,
            rule_id="bridge.link_created",
            rule_version="v1",
            observation=_summarize_transfer(body),
            evidence=[str(s) for s in body.session_pair],
            likely_cause=None,
            severity=_severity_from_scores(
                body.shape_match_score, body.intensity_match_score
            ),
            confidence=(
                body.shape_match_score + body.intensity_match_score
            )
            / 2.0,
            corner_tag=None,
            suggested_prescription_id=None,
        )
    )
    db.add(
        TransferLinkRow(
            id=link_id,
            driver_id=profile.id,
            created_at=created_at,
            created_by=body.created_by,
            session_pair=[str(s) for s in body.session_pair],
            link_reason=body.link_reason,
            shape_match_score=body.shape_match_score,
            intensity_match_score=body.intensity_match_score,
            divergence_points=[
                dp.model_dump(mode="json") for dp in body.divergence_points
            ],
            transferred_skills=list(body.transferred_skills),
            non_transferred_skills=list(body.non_transferred_skills),
            generated_report_id=insight_id,
        )
    )

    schema = TransferLinkSchema(
        id=link_id,
        driver_id=profile.id,
        created_at=created_at,
        created_by=body.created_by,
        session_pair=body.session_pair,
        link_reason=body.link_reason,
        shape_match_score=body.shape_match_score,
        intensity_match_score=body.intensity_match_score,
        divergence_points=body.divergence_points,
        transferred_skills=body.transferred_skills,
        non_transferred_skills=body.non_transferred_skills,
        generated_report_id=insight_id,
    )
    return schema, new_pair


async def _validate_pair_bridgeable(
    db: AsyncSession, sessions: list[SessionRow]
) -> None:
    """T026: enforce that the session pair shares a master_track_id
    and a car_class. Raises 422 with a stable detail string on
    violation.

    Both sessions must have `track_id` and `car_id` in their
    manifest, and both must resolve to existing catalog rows. Any
    of those preconditions failing collapses to a single
    `session_unbridgeable` detail — we don't enumerate which side
    or which field, because the caller already knows their own
    sessions and the per-field reason isn't actionable from the
    API surface.
    """
    track_ids: list[UUID] = []
    car_ids: list[UUID] = []
    for s in sessions:
        manifest = s.manifest or {}
        raw_track = manifest.get("track_id")
        raw_car = manifest.get("car_id")
        if not raw_track or not raw_car:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=ErrorCode.SESSION_UNBRIDGEABLE,
            )
        track_ids.append(UUID(str(raw_track)))
        car_ids.append(UUID(str(raw_car)))

    track_rows = (
        (
            await db.execute(
                select(TrackLayoutRow).where(
                    TrackLayoutRow.id.in_(track_ids)
                )
            )
        )
        .scalars()
        .all()
    )
    if len(track_rows) != len(set(track_ids)):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=ErrorCode.SESSION_UNBRIDGEABLE,
        )
    masters = {r.master_track_id for r in track_rows}
    if len(masters) != 1:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=ErrorCode.INCOMPATIBLE_TRACK,
        )

    car_rows = (
        (
            await db.execute(
                select(CarModelRow).where(CarModelRow.id.in_(car_ids))
            )
        )
        .scalars()
        .all()
    )
    if len(car_rows) != len(set(car_ids)):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=ErrorCode.SESSION_UNBRIDGEABLE,
        )
    classes = {r.car_class for r in car_rows}
    if len(classes) != 1:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=ErrorCode.INCOMPATIBLE_CAR_CLASS,
        )


def _row_to_schema(row: TransferLinkRow) -> TransferLinkSchema:
    return TransferLinkSchema(
        id=row.id,
        driver_id=row.driver_id,
        created_at=row.created_at,
        created_by=row.created_by,
        session_pair=tuple(UUID(s) for s in row.session_pair),
        link_reason=row.link_reason,
        shape_match_score=row.shape_match_score,
        intensity_match_score=row.intensity_match_score,
        divergence_points=tuple(row.divergence_points or []),
        transferred_skills=tuple(row.transferred_skills or []),
        non_transferred_skills=tuple(row.non_transferred_skills or []),
        generated_report_id=row.generated_report_id,
        usefulness_rating=row.usefulness_rating,  # T023
        rated_at=row.rated_at,  # T023
    )


# T021 (sprint2-backend) — paginated driver-scoped index. Sorted
# newest-first so the "recent links" view doesn't need a client
# sort. Cross-driver isolation: path's driver_id must match the
# authenticated user's profile.id, otherwise 404 (not 403) so
# callers can't enumerate drivers.
@driver_router.get(
    "/{driver_id}/bridge/links",
    response_model=TransferLinkList,
    responses={404: {"description": "driver_not_found"}},
)
async def list_driver_bridge_links(
    driver_id: UUID,
    user: Annotated[UserRow, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
    limit: Annotated[int, Query(ge=1, le=_MAX_LIMIT)] = _DEFAULT_LIMIT,
    offset: Annotated[int, Query(ge=0)] = 0,
) -> TransferLinkList:
    profile = (
        await db.execute(
            select(DriverProfileRow).where(
                DriverProfileRow.user_id == user.id
            )
        )
    ).scalar_one_or_none()
    if profile is None or profile.id != driver_id:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=ErrorCode.DRIVER_NOT_FOUND,
        )

    total = (
        await db.execute(
            select(func.count(TransferLinkRow.id)).where(
                TransferLinkRow.driver_id == driver_id
            )
        )
    ).scalar_one()

    rows = (
        (
            await db.execute(
                select(TransferLinkRow)
                .where(TransferLinkRow.driver_id == driver_id)
                .order_by(TransferLinkRow.created_at.desc())
                .limit(limit)
                .offset(offset)
            )
        )
        .scalars()
        .all()
    )
    return TransferLinkList(
        items=tuple(_row_to_schema(r) for r in rows),
        total=int(total),
        limit=limit,
        offset=offset,
    )


# T046 (sprint2-backend) — suggest candidate sessions to pair with
# the source. Filters: same master_track_id, same car_class, within
# 60 days of source.created_at, exclude source itself, must belong
# to the authenticated driver.
_SUGGEST_WINDOW = timedelta(days=60)


@router.get(
    "/suggest_links",
    response_model=BridgeSuggestLinkList,
    responses={
        404: {"description": "session_not_found"},
        422: {"description": "session_unbridgeable"},
    },
)
async def suggest_bridge_links(
    session_id: Annotated[UUID, Query()],
    user: Annotated[UserRow, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
    cache: Annotated[SuggestCache, Depends(get_suggest_cache)],
) -> BridgeSuggestLinkList:
    profile = (
        await db.execute(
            select(DriverProfileRow).where(
                DriverProfileRow.user_id == user.id
            )
        )
    ).scalar_one_or_none()
    if profile is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=ErrorCode.SESSION_NOT_FOUND,
        )

    source = (
        await db.execute(
            select(SessionRow)
            .where(SessionRow.id == session_id)
            .where(SessionRow.driver_id == profile.id)
        )
    ).scalar_one_or_none()
    if source is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=ErrorCode.SESSION_NOT_FOUND,
        )

    # T048: cache hit short-circuits the catalog joins. Lookup is
    # AFTER ownership check so a 404 on cross-driver access can't be
    # bypassed by a poisoned cache entry.
    cached = cache.get(session_id)
    if cached is not None:
        return BridgeSuggestLinkList.model_validate_json(cached)

    src_track_raw = (source.manifest or {}).get("track_id")
    src_car_raw = (source.manifest or {}).get("car_id")
    if not src_track_raw or not src_car_raw:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=ErrorCode.SESSION_UNBRIDGEABLE,
        )
    src_track_row = (
        await db.execute(
            select(TrackLayoutRow).where(
                TrackLayoutRow.id == UUID(str(src_track_raw))
            )
        )
    ).scalar_one_or_none()
    src_car_row = (
        await db.execute(
            select(CarModelRow).where(
                CarModelRow.id == UUID(str(src_car_raw))
            )
        )
    ).scalar_one_or_none()
    if src_track_row is None or src_car_row is None:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=ErrorCode.SESSION_UNBRIDGEABLE,
        )
    src_master = src_track_row.master_track_id
    src_class = src_car_row.car_class

    # Pull candidate sessions in the recency window (driver-scoped,
    # exclude source). One query gets the candidate set; we then
    # filter in-Python by resolving each candidate's track/car
    # against the catalog. Acceptable for typical session counts
    # since this endpoint is cacheable per-source (T048).
    window_start = source.created_at - _SUGGEST_WINDOW
    window_end = source.created_at + _SUGGEST_WINDOW
    candidate_rows = (
        (
            await db.execute(
                select(SessionRow)
                .where(SessionRow.driver_id == profile.id)
                .where(SessionRow.id != session_id)
                .where(SessionRow.created_at >= window_start)
                .where(SessionRow.created_at <= window_end)
                .order_by(SessionRow.created_at.desc())
            )
        )
        .scalars()
        .all()
    )

    # Batch-resolve all candidate track/car ids in one round trip
    # each so we don't N+1 the catalog lookup.
    cand_track_ids: set[UUID] = set()
    cand_car_ids: set[UUID] = set()
    cand_meta: list[tuple[SessionRow, UUID, UUID]] = []
    for c in candidate_rows:
        manifest = c.manifest or {}
        t_raw = manifest.get("track_id")
        c_raw = manifest.get("car_id")
        if not t_raw or not c_raw:
            continue
        t_id = UUID(str(t_raw))
        c_id = UUID(str(c_raw))
        cand_track_ids.add(t_id)
        cand_car_ids.add(c_id)
        cand_meta.append((c, t_id, c_id))

    track_master_by_id: dict[UUID, UUID] = {}
    if cand_track_ids:
        for tr in (
            (
                await db.execute(
                    select(TrackLayoutRow).where(
                        TrackLayoutRow.id.in_(cand_track_ids)
                    )
                )
            )
            .scalars()
            .all()
        ):
            track_master_by_id[tr.id] = tr.master_track_id
    car_class_by_id: dict[UUID, str] = {}
    if cand_car_ids:
        for cr in (
            (
                await db.execute(
                    select(CarModelRow).where(
                        CarModelRow.id.in_(cand_car_ids)
                    )
                )
            )
            .scalars()
            .all()
        ):
            car_class_by_id[cr.id] = cr.car_class

    # T047 — primary sort: same TrackLayout id as source ranks
    # ahead of merely same master_track_id (a sim-vs-sim same-layout
    # pair is more directly comparable than cross-layout). Secondary
    # sort: created_at DESC (recency). Composite key — 0 for same-
    # track lands before 1 (different-track-same-master); negated
    # timestamp gives DESC.
    src_track_id = src_track_row.id
    matched_meta: list[
        tuple[BridgeSuggestLinkCandidate, UUID, datetime]
    ] = []
    for sess, t_id, c_id in cand_meta:
        if track_master_by_id.get(t_id) != src_master:
            continue
        if car_class_by_id.get(c_id) != src_class:
            continue
        matched_meta.append(
            (
                BridgeSuggestLinkCandidate(
                    session_id=sess.id,
                    created_at=sess.created_at,
                ),
                t_id,
                sess.created_at,
            )
        )
    matched_meta.sort(
        key=lambda x: (
            0 if x[1] == src_track_id else 1,
            -x[2].timestamp(),
        )
    )
    response = BridgeSuggestLinkList(
        source_session_id=session_id,
        candidates=tuple(c for c, _, _ in matched_meta),
    )
    cache.put(session_id, response.model_dump_json().encode())
    return response
