"""T215 — Driver-facing prescription accept endpoint.
T216 — Symmetric skip endpoint.
T217 — Driver-scoped list endpoint with status filter.

The driver receives ActionPrescriptions in 'proposed' status
(generated by `infra.prescription_generator`). T215 flips status
to 'accepted' + stamps accepted_at; T216 flips status to 'skipped'
(no timestamp — there's nothing to follow up on); T217 returns
the driver's prescriptions filtered by status.

T217 lives on a second router with prefix `/api/v1/driver` to
honor the URL shape `/api/v1/driver/:id/prescriptions`. The
status filter `?status=open` (the default) maps to the union
`{proposed, accepted, in_progress}` — the actionable lifecycle
states. Other values filter exactly so callers can request
specific terminal states (e.g. `?status=skipped`).

Auth posture matches `sessions.get_session` and T205's flag
endpoint: 404 collapses "doesn't exist" with "exists but isn't
yours" so the API doesn't leak prescription IDs across users.

Idempotent — calling accept on an already-accepted prescription
is a 200 no-op (the original `accepted_at` stamp is preserved).
This protects against double-tap UIs without needing a
client-side debounce.
"""

from datetime import UTC, datetime
from typing import Annotated, Any
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, Query, status
from lap_schemas.v1 import (
    ActionPrescriptionList,
    ActionPrescriptionListItem,
)
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.deps import get_current_user, get_db
from app.error_codes import ErrorCode
from infra.orm import ActionPrescription as ActionPrescriptionRow
from infra.orm import DriverProfile as DriverProfileRow
from infra.orm import User as UserRow

router = APIRouter(prefix="/api/v1/prescriptions", tags=["prescriptions"])
driver_router = APIRouter(prefix="/api/v1/driver", tags=["prescriptions"])

# T217 — actionable lifecycle states. `?status=open` expands to
# this set; any other status value is matched exactly so callers
# can probe terminal states without a second endpoint.
_OPEN_STATUSES = ("proposed", "accepted", "in_progress")


async def _load_owned_prescription(
    db: AsyncSession,
    *,
    user: UserRow,
    prescription_id: UUID,
) -> ActionPrescriptionRow:
    """Resolve (driver_id, prescription_id) for the current user.
    Raises 404 for both unknown and not-owned — same posture as
    `sessions.get_session` so prescription IDs don't leak across
    users."""
    profile = (
        await db.execute(
            select(DriverProfileRow).where(
                DriverProfileRow.user_id == user.id
            )
        )
    ).scalar_one_or_none()
    prescription = (
        await db.execute(
            select(ActionPrescriptionRow).where(
                ActionPrescriptionRow.id == prescription_id
            )
        )
    ).scalar_one_or_none()
    if (
        prescription is None
        or profile is None
        or prescription.driver_id != profile.id
    ):
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=ErrorCode.PRESCRIPTION_NOT_FOUND,
        )
    return prescription


@router.post("/{prescription_id}/accept")
async def accept_prescription(
    prescription_id: UUID,
    user: Annotated[UserRow, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
) -> dict[str, Any]:
    prescription = await _load_owned_prescription(
        db, user=user, prescription_id=prescription_id
    )
    if prescription.status != "accepted":
        prescription.status = "accepted"
        prescription.accepted_at = datetime.now(UTC)
        await db.commit()
    return {
        "id": str(prescription.id),
        "status": prescription.status,
    }


@router.post("/{prescription_id}/skip")
async def skip_prescription(
    prescription_id: UUID,
    user: Annotated[UserRow, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
) -> dict[str, Any]:
    prescription = await _load_owned_prescription(
        db, user=user, prescription_id=prescription_id
    )
    if prescription.status != "skipped":
        prescription.status = "skipped"
        await db.commit()
    return {
        "id": str(prescription.id),
        "status": prescription.status,
    }


@router.post("/{prescription_id}/flag-wrong")
async def flag_prescription_wrong(
    prescription_id: UUID,
    user: Annotated[UserRow, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
) -> dict[str, Any]:
    """T008 (sprint2) — record a user-flagged false positive.

    Sets `flagged_wrong_at` once; subsequent calls are no-ops so
    the timestamp reflects when the user first reported the
    suggestion as wrong (not the most recent click). The flag is
    orthogonal to lifecycle status — flagging doesn't change
    `status`, so a flagged-but-completed prescription stays
    completed.

    T011 will aggregate these flags per rule to decrement the
    rule's confidence score; T008 just records them.
    """
    prescription = await _load_owned_prescription(
        db, user=user, prescription_id=prescription_id
    )
    if prescription.flagged_wrong_at is None:
        prescription.flagged_wrong_at = datetime.now(UTC)
        await db.commit()
    return {
        "id": str(prescription.id),
        "status": prescription.status,
        "flagged_wrong_at": prescription.flagged_wrong_at.isoformat(),
    }


@driver_router.get(
    "/{driver_id}/prescriptions",
    response_model=ActionPrescriptionList,
)
async def list_driver_prescriptions(
    driver_id: UUID,
    user: Annotated[UserRow, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db)],
    status_filter: Annotated[str, Query(alias="status")] = "open",
) -> ActionPrescriptionList:
    profile = (
        await db.execute(
            select(DriverProfileRow).where(
                DriverProfileRow.user_id == user.id
            )
        )
    ).scalar_one_or_none()
    # Cross-driver enumeration must collapse to 404 — same posture
    # as `sessions.get_session` so driver_ids aren't probeable.
    if profile is None or profile.id != driver_id:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=ErrorCode.DRIVER_NOT_FOUND,
        )
    stmt = select(ActionPrescriptionRow).where(
        ActionPrescriptionRow.driver_id == driver_id
    )
    if status_filter == "open":
        stmt = stmt.where(
            ActionPrescriptionRow.status.in_(_OPEN_STATUSES)
        )
    else:
        stmt = stmt.where(
            ActionPrescriptionRow.status == status_filter
        )
    rows = (await db.execute(stmt)).scalars().all()
    items = tuple(
        ActionPrescriptionListItem(
            id=row.id,
            driver_id=row.driver_id,
            weakness_episode_id=row.weakness_episode_id,
            created_at=row.created_at,
            priority=row.priority,
            title=row.title,
            rationale=row.rationale,
            drill_template_id=row.drill_template_id,
            success_condition=row.success_condition,
            status=row.status,
            accepted_at=row.accepted_at,
        )
        for row in rows
    )
    return ActionPrescriptionList(items=items, total=len(items))
